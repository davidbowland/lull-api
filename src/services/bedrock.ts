import { BedrockRuntimeClient, InvokeModelCommand } from '@aws-sdk/client-bedrock-runtime'
import Ajv from 'ajv'

import { Prompt, ToolSchema } from '../types'
import { log, logDebug, logError } from '../utils/logging'

// maxAttempts 4 against transient Bedrock throttling, over the SDK's default of 3. The backoff
// sleep is not the cost; the retried call is -- an attempt re-runs a generation rather than
// resuming it, and a 32000-token call is ~410s (measured below), so one retry of a serial
// batch-then-review pair is ~820s inside a 900s Lambda that has already spent time elsewhere.
// Every caller shares this client, including scripts/, which carries no Lambda ceiling at all; the
// fix if the logs ever show one is a second client with its own maxAttempts for the 900s
// generators, not a smaller number here.
//
// Nothing on the request path may ever reach this module. A Bedrock call cannot fit inside a
// request under any circumstances, which is why phrases are generated by the async puzzle builder
// and handed to the generators in memory.
const runtimeClient = new BedrockRuntimeClient({ maxAttempts: 4, region: 'us-east-1' })

// Standard JSON Schema mode, matching Anthropic's tool input_schema format, so one schema object
// drives both the tool definition sent to the model and the response validation below.
const ajv = new Ajv()

// Tool schemas are fixed module-level objects reused on every invocation, so the compiled
// validator is cached per schema object rather than re-parsed on every call.
const validatorCache = new WeakMap<Record<string, any>, ReturnType<typeof ajv.compile>>()

const getValidator = (schema: Record<string, any>): ReturnType<typeof ajv.compile> => {
  const cached = validatorCache.get(schema)
  if (cached) {
    return cached
  }
  const validate = ajv.compile(schema)
  validatorCache.set(schema, validate)
  return validate
}

// Context values may originate from prior LLM output, which is untrusted. Escaping </> stops it
// breaking out of the <context> XML tags in the prompt templates.
//
// & FIRST, and the order is the whole of the correctness. Escape < before & and the & in the &lt;
// just produced is escaped in turn, so every tag character double-encodes. Omit the & rule and the
// literal characters `&lt;` pass through and re-decode to `<` in any XML-aware reader.
const escapeXml = (value: string): string => value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

// A replacer function (not a string) avoids Node interpreting $&/$`/$'-style sequences
// that might appear in untrusted context values as replacement patterns.
const buildPromptContents = (prompt: Prompt, context?: Record<string, any>): string =>
  context ? prompt.contents.replace('${context}', () => escapeXml(JSON.stringify(context))) : prompt.contents

const buildRequestBody = (prompt: Prompt, tool: ToolSchema, contents: string) => ({
  anthropic_version: prompt.config.anthropicVersion,
  max_tokens: prompt.config.maxTokens,
  messages: [{ content: contents, role: 'user' }],
  output_config: { effort: prompt.config.thinkingEffort },
  // Forced tool_choice ("tool"/"any") is not supported alongside extended thinking, so we can
  // only steer the model to call the tool via "auto" and validate that it did so below.
  thinking: { type: 'adaptive' },
  tool_choice: { type: 'auto' },
  tools: [tool],
})

const sendToBedrock = async (command: InvokeModelCommand, model: string) => {
  try {
    return await runtimeClient.send(command)
  } catch (error: unknown) {
    const err = error as {
      $metadata?: {
        attempts?: number
        httpStatusCode?: number
        requestId?: string
        totalRetryDelay?: number
      }
      message?: string
      name?: string
    } | null
    log('Bedrock invocation failed', {
      attempts: err?.$metadata?.attempts,
      errorName: err?.name,
      httpStatusCode: err?.$metadata?.httpStatusCode,
      message: err?.message,
      model,
      requestId: err?.$metadata?.requestId,
      totalRetryDelay: err?.$metadata?.totalRetryDelay,
    })
    throw error
  }
}

const decodeResponseBody = (body: Uint8Array | undefined, model: string) => {
  try {
    return JSON.parse(new TextDecoder().decode(body))
  } catch (error: unknown) {
    log('Failed to parse Bedrock response body as JSON', {
      message: (error as Error | null)?.message,
      model,
    })
    throw error
  }
}

const extractJson = (input: string): string => {
  const cleaned = input.replace(/(^\s*|\s*```(?:json)?\s*|\s*$)/gs, '')
  return cleaned.match(/{.*}/s)?.[0] ?? cleaned
}

// Thinking and the tool call share one max_tokens budget, so a run that spends the whole budget
// thinking returns no tool_use block at all and the batch is lost. Logged on every invocation and
// not only on failure: a failure count says nothing without knowing how much headroom a healthy
// run leaves, and that headroom is what says whether the effort level can come down.
//
// The token budgets these numbers size, measured: create-phrases runs at maxTokens 32000, where a
// six-phrase call costs ~12,453 output tokens (39%) and an eighteen-phrase call cost 24,816 (78%)
// and truncated on a bad run -- which is why services/phrases.ts splits the request into
// concurrent calls of six and contains a failure per call.
//
// 32000 stayed after a runaway spent the whole budget on reasoning alone, and the reason is WALL
// CLOCK. generatePhrases is a Promise.all and a runaway runs to the ceiling by definition, with
// reviewPhrases serial after it: at ~75 tok/s, 32000 is ~440s plus review's ~205s inside 900s,
// while 48000 is ~820s together and 64000 means review never runs. A Lambda timeout does not run
// create-phrase-puzzles.ts's catch, so raising this trades a contained six-phrase loss that alarms
// for an uncontained whole-night loss that logs nothing but `Task timed out`. Raising
// PHRASES_PER_CALL spends the same headroom; measure before moving either.
//
// The line carries its own denominator and its own split. `outputTokens: 32000` alone is the same
// number for a long healthy answer and for a night spent entirely on reasoning, and the cap it is
// read against lives in a prompt file. maxTokens makes headroom one division on one line;
// thinkingTokens says where the budget went. Both are optional-chained, because the runs this
// instrument exists for are the ones that went wrong.
const logModelUsage = (
  modelResponse: {
    stop_reason?: string
    usage?: { input_tokens?: number; output_tokens?: number; output_tokens_details?: { thinking_tokens?: number } }
  },
  tool: ToolSchema,
  model: string,
  maxTokens: number,
): void => {
  // ERROR on max_tokens and `log` on everything else. A truncated generation costs a night's
  // puzzles and the only alarm here is a subscription filtering on level="ERROR"; every other stop
  // reason is a healthy run and must not reach it, or that alarm becomes noise.
  const write = modelResponse.stop_reason === 'max_tokens' ? logError : log
  write('Model invocation complete', {
    inputTokens: modelResponse.usage?.input_tokens,
    maxTokens,
    model,
    outputTokens: modelResponse.usage?.output_tokens,
    stopReason: modelResponse.stop_reason,
    thinkingTokens: modelResponse.usage?.output_tokens_details?.thinking_tokens,
    toolName: tool.name,
  })
}

const extractModelPayload = (
  modelResponse: {
    content: { type: string; input?: unknown; name?: string; text?: string }[]
    stop_reason: string
  },
  tool: ToolSchema,
  model: string,
): unknown => {
  const toolUseBlock = modelResponse.content.find((b) => b.type === 'tool_use')
  if (toolUseBlock) {
    return toolUseBlock.input
  }

  const textBlock = modelResponse.content.find((b) => b.type === 'text')
  if (!textBlock?.text) {
    // Same conditional and reasoning as logModelUsage above: this is the shape a max_tokens stop
    // actually arrives in.
    const write = modelResponse.stop_reason === 'max_tokens' ? logError : log
    write('Model response missing tool_use block and text block', {
      blockTypes: modelResponse.content.map((b) => b.type),
      model,
      stopReason: modelResponse.stop_reason,
      toolName: tool.name,
    })
    throw new Error(`Model response contained no ${tool.name} tool call`)
  }

  log('Model replied without invoking the expected tool; falling back to text extraction', {
    model,
    toolName: tool.name,
  })
  try {
    return JSON.parse(extractJson(textBlock.text))
  } catch (error: unknown) {
    log('Failed to parse JSON from fallback text response', {
      message: (error as Error | null)?.message,
      model,
      textLength: textBlock.text.length,
    })
    throw error
  }
}

const VALIDATION_FAILURE_PREVIEW_LENGTH = 500

const validateResponse = <T>(tool: ToolSchema, parsed: unknown): T => {
  const validate = getValidator(tool.input_schema)
  if (!validate(parsed)) {
    const errors = ajv.errorsText(validate.errors)
    // Payload detail, unlike the routine per-invocation logs, because a validation failure is
    // undebuggable without it. Truncated at production level since `parsed` may echo generated
    // game content; the full payload goes only to DEBUG_LOGGING.
    const preview = JSON.stringify(parsed).slice(0, VALIDATION_FAILURE_PREVIEW_LENGTH)
    log('Model response failed schema validation', {
      errors,
      parsedPreview: preview,
      toolName: tool.name,
    })
    logDebug('Model response failed schema validation (full payload)', {
      parsed,
      toolName: tool.name,
    })
    throw new Error(`Model response failed schema validation for tool "${tool.name}": ${errors}`)
  }
  return parsed as T
}

export const invokeModel = async <T>(prompt: Prompt, tool: ToolSchema, context?: Record<string, any>): Promise<T> => {
  const contents = buildPromptContents(prompt, context)
  logDebug('Invoking model', { contents, prompt, tool })

  const messageBody = buildRequestBody(prompt, tool, contents)
  log('Invoking model', { model: prompt.config.model, toolName: tool.name })

  const command = new InvokeModelCommand({
    body: new TextEncoder().encode(JSON.stringify(messageBody)),
    contentType: 'application/json',
    modelId: prompt.config.model,
  })

  const response = await sendToBedrock(command, prompt.config.model)
  const modelResponse = decodeResponseBody(response.body, prompt.config.model)
  // Before extraction, not after: extraction throws on the exact runs whose token counts matter most.
  logModelUsage(modelResponse, tool, prompt.config.model, prompt.config.maxTokens)
  const payload = extractModelPayload(modelResponse, tool, prompt.config.model)
  return validateResponse(tool, payload)
}
